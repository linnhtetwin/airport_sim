// Regenerate src/data/airportPositions.ts: where every airport with an ICAO code is, from
// OurAirports (public domain). The server uses it to build an airport's OpenStreetMap query
// straight away, instead of first searching OpenStreetMap for the airport (a slow query).
//
//   npm run airport-positions              download the latest airports.csv
//   npm run airport-positions -- file.csv  use a local copy
//
// Needs Node 22.18 or newer.

import { readFile, writeFile } from 'node:fs/promises';

const SOURCE = 'https://davidmegginson.github.io/ourairports-data/airports.csv';
const OUT = new URL('../src/data/airportPositions.ts', import.meta.url);
// heliports, seaplane bases etc. have no runways for the game to use
const TYPES = ['large_airport', 'medium_airport', 'small_airport'];

const local = process.argv[2];
const csv = local ? await readFile(local, 'utf8') : await (async () => {
  const res = await fetch(SOURCE, { headers: { 'User-Agent': 'AirportOpsSim/0.1 (+https://airport-ops-sim.pages.dev)' } });
  if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
  return res.text();
})();

/** RFC 4180 CSV: quoted fields may hold commas, line breaks and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [head, ...rows] = parseCsv(csv);
const col = (name) => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error(`airports.csv has no "${name}" column`);
  return i;
};
const c = { type: col('type'), icao: col('icao_code'), gps: col('gps_code'), lat: col('latitude_deg'), lon: col('longitude_deg') };

const best = new Map();
for (const r of rows) {
  const rank = TYPES.indexOf(r[c.type]);
  if (rank < 0) continue;
  // the official ICAO code, else a four-letter GPS code (often the ICAO code OpenStreetMap uses)
  const code = /^[A-Z0-9]{4}$/.test(r[c.icao]) ? r[c.icao] : /^[A-Z]{4}$/.test(r[c.gps]) ? r[c.gps] : '';
  const lat = Number(r[c.lat]), lon = Number(r[c.lon]);
  if (!code || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  // a code used twice: keep the bigger airport
  if (!best.has(code) || rank < best.get(code).rank) best.set(code, { rank, lat, lon });
}

const entries = [...best].sort(([a], [b]) => a.localeCompare(b));
const data = entries.map(([code, p]) => `${code}${+p.lat.toFixed(3)},${+p.lon.toFixed(3)}`).join(';');
await writeFile(OUT, `// Generated by scripts/update-airport-positions.mjs from OurAirports (public domain,
// https://ourairports.com/data/). Do not edit by hand. Server side only: it isn't needed in the
// game bundle, which only loads airports through its own site.

import type { LatLon } from '../geo/projection.ts';
import { AIRPORTS } from './airports.ts';

/** "ICAOlat,lon" entries separated by ";", sorted by code. */
const DATA = '${data}';

let index: Map<string, LatLon> | null = null;

/** Where an airport is: the preset position for preset airports, else OurAirports. */
export function airportPosition(icao: string): LatLon | null {
  const preset = AIRPORTS.find((a) => a.icao === icao);
  if (preset) return { lat: preset.lat, lon: preset.lon };
  if (!index) {
    index = new Map();
    for (const e of DATA.split(';')) {
      const [lat, lon] = e.slice(4).split(',').map(Number);
      index.set(e.slice(0, 4), { lat, lon });
    }
  }
  return index.get(icao) ?? null;
}
`);
console.log(`${entries.length} airports, ${(data.length / 1024).toFixed(0)} KB`);
